/** 结点定义(8 个,用画布坐标 x/y 定位,会自动吸附到河道上)
 *
 *  x/y: 1920×3240 画布坐标
 *  name: 占位时期名(后续由文案替换)
 *  year: 占位年份标注(后续由文案替换)
 */
export interface TimelineNodeDef {
  /** 画布 x 坐标(0~1920) */
  x: number;
  /** 画布 y 坐标(0~3240) */
  y: number;
  /** 占位名 */
  name: string;
  /** 占位年份 */
  year: string;
  /** 该结点在 path 上的 t 值,由 scene 启动时自动计算 */
  t: number;
}

